export const SIDO_NAMES: string[] = REGIONS.map((r) => r.name);

/** 주어진 시도의 시군구 목록을 반환한다. 미존재·단층제는 빈 배열 */
export function getSigungu(sido: string): string[] {
  return REGIONS.find((r) => r.name === sido)?.sigungu ?? [];
}

/** 시도 + 시군구를 지자체명으로 합성한다 (단층제는 시도만). 예: "서울특별시 강남구" */
export function composeMunicipality(sido: string, sigungu?: string): string {
  return [sido.trim(), sigungu?.trim()].filter(Boolean).join(" ");
}
